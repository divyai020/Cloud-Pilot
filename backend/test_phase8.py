"""
Cloud Pilot Phase 8 Integration & Verification Test Script
Tests AI Recommendations Engine, PDF Report Generation, CSV Export,
Ownership Security, and Empty Data Handling against real PostgreSQL.
"""
import sys
import os
from fastapi import HTTPException

sys.path.insert(0, os.path.dirname(__file__))

from app.database import check_db_connection, SessionLocal
from app.models import User, CloudAccount
from app.schemas.user import UserCreate
from app.services import auth_service, demo_service, ai_service, report_service
from app.main import app

def run_phase8_tests():
    print("=" * 70)
    print("STARTING CLOUD PILOT PHASE 8 AI RECOMMENDATIONS & REPORTS VERIFICATION")
    print("=" * 70)

    # 1. Check Routes in FastAPI Application
    routes = [r.path for r in app.routes]
    print("\n[1. Router Registration Check]")
    expected_endpoints = [
        "/api/v1/reports/pdf",
        "/api/v1/reports/csv",
        "/api/v1/reports/recommendations",
    ]
    for ep in expected_endpoints:
        assert ep in routes, f"Missing router endpoint: {ep}"
    print("All Phase 8 Report & Recommendation endpoints are registered in FastAPI!")

    # 2. Database Connection Check
    is_conn, conn_msg = check_db_connection()
    assert is_conn == True, f"Database connection failed: {conn_msg}"
    print("\n[2. Database Connection Check]")
    print("PostgreSQL connection: PASSED")

    db = SessionLocal()
    try:
        # Cleanup prior test users
        old_users = db.query(User).filter(User.email.in_(["phase8_user1@example.com", "phase8_user2@example.com", "phase8_empty@example.com"])).all()
        for u in old_users:
            db.delete(u)
        db.commit()

        # 3. Create User 1 & Seed Demo Environment
        print("\n[3. User Setup & Demo Account Creation]")
        u1_data = UserCreate(fullName="AI Reports Test User One", email="phase8_user1@example.com", password="Password123!")
        user1 = auth_service.register_user(db, u1_data)
        demo_info = demo_service.seed_demo_data(db, user=user1)
        account_id = demo_info["accountId"]
        print(f"User 1 created ({user1.id}) with Demo Account ({account_id})")

        # 4. Test AI Recommendation Engine
        print("\n[4. AI Optimization Recommendation Engine Test]")
        recs = ai_service.generate_ai_recommendations(db, user=user1, account_id=account_id)
        assert len(recs) > 0, "AI Recommendation Engine returned empty list"
        
        # Verify recommendation data schema requirements
        rec_ids = [r["recommendation_id"] for r in recs]
        categories = set(r["category"] for r in recs)
        total_savings = sum(r["estimated_savings"] for r in recs)

        for r in recs:
            assert "recommendation_id" in r
            assert "title" in r
            assert "description" in r
            assert "priority" in r
            assert "estimated_savings" in r
            assert "category" in r
            assert "created_at" in r

        print(f"Generated {len(recs)} AI recommendations across categories: {list(categories)}")
        print(f"Total Potential Estimated Savings: ${total_savings:,.2f}")
        print("Sample Recommendation:", recs[0]["title"], "-> Savings:", recs[0]["estimated_savings"])
        print("AI Recommendation Engine PASSED!")

        # 5. Test PDF Report Generation
        print("\n[5. Executive PDF Report Generation Test]")
        pdf_bytes = report_service.generate_pdf_report(db, user=user1, account_id=account_id)
        assert len(pdf_bytes) > 0
        assert pdf_bytes.startswith(b"%PDF-"), "Generated byte content is not a valid PDF document"
        print(f"PDF Report generated successfully! Size: {len(pdf_bytes):,} bytes")
        print("Executive PDF Report Generation PASSED!")

        # 6. Test CSV Export Generation
        print("\n[6. Tabular CSV Report Export Test]")
        csv_str = report_service.generate_csv_report(db, user=user1, account_id=account_id)
        assert len(csv_str) > 0
        assert "CLOUD PILOT - GOVERNANCE REPORT" in csv_str
        assert "EXECUTIVE SUMMARY METRICS" in csv_str
        assert "RECOMMENDATIONS LIST" in csv_str
        print(f"CSV Report generated successfully! Rows/Lines: {len(csv_str.splitlines())}")
        print("Tabular CSV Export PASSED!")

        # 7. Test Multi-User Ownership & Isolation Security
        print("\n[7. Multi-User Ownership & Isolation Security Test]")
        u2_data = UserCreate(fullName="AI Reports Test User Two", email="phase8_user2@example.com", password="Password123!")
        user2 = auth_service.register_user(db, u2_data)

        # User 2 attempts to fetch User 1's recommendations
        try:
            ai_service.generate_ai_recommendations(db, user=user2, account_id=account_id)
            assert False, "Should have thrown HTTP 404"
        except HTTPException as e:
            assert e.status_code == 404
            print("User 2 blocked from accessing User 1's AI recommendations (HTTP 404) PASSED!")

        # User 2 attempts to generate User 1's PDF Report
        try:
            report_service.generate_pdf_report(db, user=user2, account_id=account_id)
            assert False, "Should have thrown HTTP 404"
        except HTTPException as e:
            assert e.status_code == 404
            print("User 2 blocked from generating User 1's PDF Report (HTTP 404) PASSED!")

        # 8. Test Empty Account Zero-Data Handling
        print("\n[8. Empty Account Zero-Data Analytics & Export Test]")
        u_empty = UserCreate(fullName="Empty Reports User", email="phase8_empty@example.com", password="Password123!")
        user_empty = auth_service.register_user(db, u_empty)

        empty_account = CloudAccount(
            user_id=user_empty.id,
            account_name="Empty Environment",
            account_type="aws",
            aws_account_id="888888888888",
            status="active"
        )
        db.add(empty_account)
        db.commit()

        empty_recs = ai_service.generate_ai_recommendations(db, user=user_empty, account_id=empty_account.id)
        empty_pdf = report_service.generate_pdf_report(db, user=user_empty, account_id=empty_account.id)
        empty_csv = report_service.generate_csv_report(db, user=user_empty, account_id=empty_account.id)

        assert empty_pdf.startswith(b"%PDF-")
        assert len(empty_csv) > 0
        print("Empty Account PDF, CSV, and AI Recommendations generation PASSED!")

        print("\n" + "=" * 70)
        print("ALL PHASE 8 AI RECOMMENDATIONS & REPORT GENERATION TESTS PASSED!")
        print("=" * 70)

    finally:
        db.close()

if __name__ == "__main__":
    run_phase8_tests()
